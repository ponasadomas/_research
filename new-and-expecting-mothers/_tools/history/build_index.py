#!/usr/bin/env python3
"""Regenerate the complete thematic language bank and ordinary-record catalogue.

Research records people's words whatever the subject. The owner decides later
what to use in copy; historical eligibility fields never restrict research.

    python3 build_index.py
"""
import glob, json, os, collections

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
GROUPS = json.load(open(os.path.join(os.path.dirname(__file__), "theme_groups.json")))

rows = []
for f in sorted(glob.glob(os.path.join(ROOT, "voice", "*.jsonl"))):
    rows += [{k: v for k, v in json.loads(l).items()
              if k not in {"marketing_eligible", "evidence_use"}}
             for l in open(f) if l.strip()]
ids = collections.Counter(r['id'] for r in rows)
if any(n != 1 for n in ids.values()):
    raise SystemExit('Duplicate voice ids; catalogue not rebuilt.')

def group(r, name):
    return bool(set(r["themes"]).intersection(GROUPS[name]))

def has(r, *themes):
    return any(t in r["themes"] for t in themes)

SECTIONS = [
 ("Search and purchase triggers", "Scenes that prompted a search; payment is established separately in context.", lambda r:r["type"]=="trigger_moment"),
 ("Too much advice, too little time", "", lambda r:has(r,"information_overload","conflicting_advice","not_enough_time")),
 ("Development and everyday play", "", lambda r:group(r,"development_play")),
 ("Starting solids and family meals", "", lambda r:group(r,"solids_workload") or has(r,"choking_fear","allergen_introduction")),
 ("Returning to work and caregiver handoff", "", lambda r:has(r,"return_to_work","pumping_schedule","daycare_handoff","bottle_refusal","caregiver_handoff","caregiver_communication")),
 ("Pregnancy and postpartum support", "", lambda r:group(r,"household_coordination") or has(r,"pregnancy_activity","postpartum_recovery")),
 ("Sleep and tracking", "", lambda r:has(r,"sleep_routines","sleep","wake_windows","contact_naps","sleep_training_values")),
 ("Gear, registry, gifts and small homes", "Current physical fit, local stock and safety need separate verification.", lambda r:group(r,"gear_and_registry")),
 ("Leave, pay and childcare choices", "Historical peer rules and prices are not current guidance.", lambda r:group(r,"leave_and_childcare")),
 ("First trips and outings", "Anecdotes describe the job, not current transport or safety rules.", lambda r:group(r,"first_trips")),
 ("Paper, editable files and photo workflows", "A request for a keepsake is a different job from a care report.", lambda r:group(r,"portable_formats")),
 ("Questions, desires and fears", "", lambda r:r["type"] in ("question","desire","fear")),
 ("What failed and objections to paying", "", lambda r:r["type"] in ("tried_failed","objection","regret","failure_story") or has(r,"price_value","free_alternatives","subscription_fatigue")),
 ("Partners and the other side", "", lambda r:r["speaker"] in ("partner","relative_caregiver","gave_up_parent","skeptic")),
 ("Reported improvements", "Anecdotes, not evidence of causation or clinical effectiveness.", lambda r:r["type"]=="success_story"),
 ("Professional boundaries", "Guidance is separate from buyer demand.", lambda r:r.get("source_class")=="official_guidance"),
 ("Seller and advertising claims", "These are not independent customer voices.", lambda r:r.get("evidence_kind")=="seller_claim"),
]

def score(r):
    # favour quotable length and concrete detail; a mild engagement nudge
    n = len(r["quote"])
    s = 3 if 60 <= n <= 320 else (1 if n <= 500 else 0)
    s += 3 if r.get("source_class") in {"reddit_archive","forum","forum_oblique","qa_community"} else (1 if r.get("source_class") in {"app_review","book_review"} else 0)
    s += 1 if '"' in r["quote"] or "“" in r["quote"] else 0
    s += 1 if any(c.isdigit() for c in r["quote"]) else 0
    e = r.get("engagement") or {}
    s += min((e.get("score") or e.get("likes") or 0), 300) / 300
    return s

out = ["# Quote index", "",
       f"Generated by `_tools/build_index.py`: all {len(rows)} quotes in `voice/`, each shown once under its first matching theme.",
       "The complete machine-readable index is `quote-catalogue.jsonl`. For anything specific use",
       "`python3 _tools/query.py --theme … --speaker … --text …`.", "",
       "Every quote is verbatim. `[id]` finds the full record (URL, date, context) in `voice/`.", ""]
out += ["Research records people's words whatever the subject. The owner decides later what to use in copy. Original voice files preserve historical metadata; eligibility fields have no effect here. Context belongs with the quotation; peer claims and seller claims are not verified facts.", ""]
out += ["## Sections", ""] + [f"- {t}" for t, _, _ in SECTIONS] + [""]
used_ids = set()
for title, blurb, pred in SECTIONS + [("Other recorded experiences", "", lambda r: True)]:
    hits = sorted((r for r in rows if pred(r)), key=score, reverse=True)
    picked = [r for r in hits if r['id'] not in used_ids]
    used_ids.update(r['id'] for r in picked)
    out += [f"## {title}", ""]
    if blurb:
        out += [blurb, ""]
    out += [f"*{len(hits)} quotes in the database match; showing {len(picked)}.*", ""]
    for r in picked:
        q = " ".join(r["quote"].split())
        who = r["speaker"].replace("_", " ")
        out += [f"[{r['id']}]", "> " + r['quote'].replace('\n', '\n> '), "",
                f"— {who}, {r['stage'].replace('_', ' ')} · {r.get('source_class','unspecified')} / {r.get('evidence_kind','unspecified')}",
                f"Context: {r['context']} [Original source]({r['url']}) · [Frozen source](../{r['raw_file']})", ""]
    out.append("")
os.makedirs(os.path.join(ROOT, "synthesis"), exist_ok=True)
open(os.path.join(ROOT, "synthesis", "quote-index.md"), "w").write("\n".join(out))
open(os.path.join(ROOT, 'synthesis', 'quote-catalogue.jsonl'), 'w').write(
    ''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in rows))
open(os.path.join(ROOT, 'synthesis', 'language-bank-counts.json'), 'w').write(
    json.dumps({'entries': len(rows), 'distinct_quote_ids': len(ids),
                'source_records': len(rows), 'subject_exclusions': 0,
                'historically_marked_records_included': sum(
                    json.loads(l).get('marketing_eligible') is False
                    for f in glob.glob(os.path.join(ROOT, 'voice', '*.jsonl'))
                    for l in open(f) if l.strip())}, indent=2) + '\n')
assert used_ids == set(ids)
print("sections", len(SECTIONS) + 1, "| records", len(used_ids), "| duplicate ids 0")
