#!/usr/bin/env python3
"""Audit one niche after reading: coverage, descriptive label sweep, counts, merged copy, spot-check sample.
    python3 -I audit_niche.py <niche> <read-label> [<read-label> ...] [--check-only]
--check-only checks coverage and labels without rewriting any artifacts.
Writes <niche>/synthesis/counts.md, audit-safety-hits.tsv, audit-spotcheck.md and voice-merged/all.jsonl
(a derived copy; reader files are never edited)."""
import collections, glob, json, os, random, re, sys
R = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
niche = sys.argv[1]
check_only = "--check-only" in sys.argv[2:]
labels = [arg for arg in sys.argv[2:] if arg != "--check-only"]
D = os.path.join(R, niche)
recs = []
for f in sorted(glob.glob(os.path.join(D, "voice", "*.jsonl"))):
    for l in open(f):
        if l.strip():
            r = json.loads(l); r["_file"] = os.path.basename(f); recs.append(r)
# Historical labels only: no quote is actively restricted.
restr = set()
rp = os.path.join(D, "synthesis", "restricted-ids.md")
if os.path.exists(rp):
    for line in open(rp):
        if line.startswith("|") and not line.startswith("| id") and not line.startswith("|---"):
            cell = line.split("|")[1]
            for m in re.finditer(r"([a-z]{2,3}\d{1,2})-(\d{4})((?:\s*,\s*\d{4})*)", cell):
                restr.add(f"{m.group(1)}-{m.group(2)}")
                for extra in re.findall(r"\d{4}", m.group(3)): restr.add(f"{m.group(1)}-{extra}")
            for m in re.finditer(r"([a-z]{2,3}\d{1,2})-(\d{4})–(\d{4})", cell):
                for i in range(int(m.group(2)), int(m.group(3)) + 1): restr.add(f"{m.group(1)}-{i:04d}")
# coverage
assigned = set()
for lab in labels:
    for l in open(os.path.join(D, "_raw", "reddit", lab, "chunks.jsonl")):
        assigned |= set(json.loads(l)["units"])
cited = collections.Counter(r["raw_file"] for r in recs)
uncited = sorted(u for u in assigned if u not in cited)
ledgers = " ".join(open(f).read() for f in glob.glob(os.path.join(D, "sources", "reddit-reading-*.md")))
unexplained = [u for u in uncited if os.path.basename(u)[:-4] not in ledgers and os.path.basename(u)[:-4].split("-", 1)[1] not in ledgers]
# Descriptive sweep; a match never excludes evidence.
SAFE = re.compile(r"kill myself|suicid|self.?harm|want to die|hurt (?:myself|my baby|him|her)|shak(?:e|ing|en) (?:the|my|him|her)|smack|spank|slap|hit (?:him|her|my)|abus|sids|stopped breathing|not breathing|face down|suffocat|smother|died|dead\b|funeral|psychosis|intrusive thought|cps\b|police|asleep at the wheel|car accident|crash", re.I)
hits = [(r["id"], m.group(0), r["quote"][:160].replace("\t", " ").replace("\n", " ")) for r in recs if (m := SAFE.search(r["quote"]))]
if check_only:
    print(json.dumps({"quotes": len(recs), "assigned": len(assigned), "units_quoted": len(cited),
                      "assigned_units_quoted": len(assigned & set(cited)), "uncited": len(uncited),
                      "unexplained": len(unexplained), "historically_marked": len(restr),
                      "active_restrictions": 0, "safety_hits": len(hits)}))
    for u in unexplained:
        print("UNEXPLAINED", u)
    sys.exit(1 if unexplained else 0)
open(os.path.join(D, "synthesis", "audit-safety-hits.tsv"), "w").write("id\tmatch\tformerly_restricted\tquote\n" + "".join(f"{i}\t{m}\t{i in restr}\t{q}\n" for i, m, q in hits))
# merged copy with conventions applied
os.makedirs(os.path.join(D, "voice-merged"), exist_ok=True)
FATHER = re.compile(r"\b(?:my wife|my (?:girlfriend|fiancee|partner) (?:is|was) breastfeeding|as a dad|as the dad|i'?m the dad|dad here|father here|my wife's)\b", re.I)
relabeled = 0
with open(os.path.join(D, "voice-merged", "all.jsonl"), "w") as out:
    for r in recs:
        m = dict(r); m.pop("_file", None)
        if m["speaker"] == "parent_unspecified" and (FATHER.search(m["quote"]) or FATHER.search(m.get("context", ""))):
            m["speaker"] = "partner"; m["speaker_relabel"] = "orchestrator: father convention"; relabeled += 1
        m["formerly_restricted"] = m["id"] in restr
        m["restricted"] = False
        out.write(json.dumps(m, ensure_ascii=False) + "\n")
# counts
def table(c, title):
    return f"\n### {title}\n\n| value | quotes |\n|---|---:|\n" + "".join(f"| {k} | {v} |\n" for k, v in c.most_common())
merged = [json.loads(l) for l in open(os.path.join(D, "voice-merged", "all.jsonl"))]
sp = collections.Counter(r["speaker"] for r in merged); st = collections.Counter(r["stage"] for r in merged)
ty = collections.Counter(r["type"] for r in merged); src = collections.Counter(r["source"] for r in merged)
th = collections.Counter(t for r in merged for t in (r["themes"] if isinstance(r["themes"], list) else [r["themes"]]))
files = collections.Counter(r["_file"] for r in recs)
units_quoted = len(cited)
md = f"""# Counts — {niche}

Generated by `../../_shared/_tools/audit_niche.py` from `voice/*.jsonl` (merged copy: `voice-merged/all.jsonl`). **Counts are counts of quotes chosen by readers, never of people or prevalence.** Every number in `findings.md` comes from this file.

| measure | value |
|---|---:|
| quotes | {len(recs)} |
| reader voice files | {len(files)} |
| units assigned for full reading | {len(assigned)} |
| units with at least one quote | {units_quoted} |
| units read with no quote | {len(uncited)} |
| of those, not named in any reader ledger | {len(unexplained)} |
| historically marked quote ids (no effect) | {len(restr & set(r['id'] for r in recs))} |
| active quote restrictions | 0 |
| safety-regex hits (inspected by hand, see audit-safety-hits.tsv) | {len(hits)} |
| of those, not historically marked | {sum(1 for i,_,_ in hits if i not in restr)} |
| speakers relabelled to `partner` in the merged copy | {relabeled} |
""" + table(files, "Quotes per reader file") + table(sp, "Speaker (merged copy)") + table(st, "Stage") + table(ty, "Type") + table(src, "Source") + table(collections.Counter(dict(th.most_common(60))), "Top 60 themes")
open(os.path.join(D, "synthesis", "counts.md"), "w").write(md)
# spot-check sample
random.seed(20261025)
sample = random.sample(recs, 20)
sc = "# Spot check — 20 random quotes (seed 20261025)\n\nOrchestrator reads each against its unit: does the context match, is the speaker right?\n\n"
for r in sample:
    sc += f"## {r['id']} · {r['speaker']} · {r['stage']} · {r['type']}\n- raw: `{r['raw_file']}`\n- context: {r['context']}\n> {r['quote'][:400]}\n- verdict: \n\n"
open(os.path.join(D, "synthesis", "audit-spotcheck.md"), "w").write(sc)
print(json.dumps({"quotes": len(recs), "assigned": len(assigned), "units_quoted": units_quoted, "uncited": len(uncited), "unexplained": len(unexplained), "historically_marked": len(restr), "active_restrictions": 0, "safety_hits": len(hits), "hits_without_historical_mark": sum(1 for i,_,_ in hits if i not in restr), "relabeled": relabeled}))
for u in unexplained[:30]: print("UNEXPLAINED", u)
