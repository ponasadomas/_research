#!/usr/bin/env python3
"""Rebuild this build's derived corpus with the shared audit.

Keep the historical spot-check worksheet and the readers' speaker attributions.
The shared father-expression heuristic also matches pregnant authors with wives,
quoted speech and phrases such as 'having the father here'. It cannot establish
the speaker's role in this corpus. Original voice records are never modified.
"""
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys


BUILD = Path(__file__).resolve().parent.parent
RESEARCH = BUILD.parent


def main():
    speakers = {}
    for path in sorted((BUILD / "voice").glob("*.jsonl")):
        for line in path.read_text().splitlines():
            if line.strip():
                record = json.loads(line)
                if record["id"] in speakers:
                    raise ValueError(f"Duplicate source id: {record['id']}")
                speakers[record["id"]] = record["speaker"]

    spotcheck = BUILD / "synthesis/audit-spotcheck.md"
    original_spotcheck = spotcheck.read_bytes()
    counts_path = BUILD / "synthesis/counts.md"
    previous_counts = counts_path.read_text()
    supplement_marker = "\n## Re-reading and integration"
    supplement = (supplement_marker + previous_counts.split(supplement_marker, 1)[1]
                  if supplement_marker in previous_counts else "")
    try:
        subprocess.run(
            [sys.executable, "-I", str(RESEARCH / "_shared/_tools/audit_niche.py"),
             "pregnancy-birth", "read-v1", "read-w2", "read-w3"],
            cwd=RESEARCH, check=True,
        )
    finally:
        spotcheck.write_bytes(original_spotcheck)

    merged = BUILD / "voice-merged/all.jsonl"
    records = [json.loads(line) for line in merged.read_text().splitlines() if line.strip()]
    restored = []
    for record in records:
        if record["speaker"] != speakers[record["id"]]:
            restored.append(record["id"])
            record["speaker"] = speakers[record["id"]]
            record.pop("speaker_relabel", None)
    merged.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records))

    counts = counts_path.read_text()
    speaker_counts = Counter(r["speaker"] for r in records)
    table = ("### Speaker (merged copy)\n\n| value | quotes |\n|---|---:|\n"
             + "".join(f"| {speaker} | {n} |\n" for speaker, n in speaker_counts.most_common()))
    counts = re.sub(r"### Speaker \(merged copy\)[\s\S]*?(?=\n### Stage)", table, counts)
    counts = re.sub(r"(\| speakers relabelled to `partner` in the merged copy \| )\d+( \|)",
                    r"\g<1>0\2", counts)
    counts = counts.replace("Generated by `../../_shared/_tools/audit_niche.py`",
                            "Generated by `../../_shared/_tools/audit_niche.py` via `_tools/rebuild_voice.py`")
    counts = counts.replace("Every number in `findings.md` comes from this file.",
                            "Current corpus totals are below; findings preserve explicitly historical wave counts. "
                            "Re-reading, citation and backlog counts below come from the unchanged manifests, "
                            "ledgers, digest indexes and current findings.")
    for old, new in {
        "| units assigned for full reading |": "| original-manifest raw paths assigned for full reading |",
        "| units with at least one quote |": "| raw-file paths with at least one quote (all voice) |",
        "| units read with no quote |": "| original-manifest raw paths now without a quote |",
        "safety-regex hits (inspected by hand, see audit-safety-hits.tsv)":
            "descriptive regex matches (see audit-safety-hits.tsv; no exclusion)",
    }.items():
        counts = counts.replace(old, new)
    counts_path.write_text(counts + supplement)
    print(f"Reader speaker labels retained for all {len(records)} records; "
          f"{len(restored)} heuristic relabels rejected: {', '.join(restored)}")


if __name__ == "__main__":
    main()
